from abc import ABC, abstractmethod


class EmbedError(Exception):
    """임베딩 단계에서 복구 불가능한 오류(모델 없음, 세션 실패 등)."""


class Embedder(ABC):
    #------------------------------------------------------------------
    # 모델 적재 보장 (지연 로딩)
    # -out: load_ms = 실제 로딩 밀리초(이미 로드면 0.0)
    #------------------------------------------------------------------
    @abstractmethod
    def ensure_loaded(self):
        ...

    #------------------------------------------------------------------
    # 로드 여부
    # -out: bool
    #------------------------------------------------------------------
    @abstractmethod
    def is_ready(self):
        ...

    #------------------------------------------------------------------
    # 텍스트 목록 -> 벡터 행렬 (L2 정규화)
    # -out: (N, dim) float32
    #------------------------------------------------------------------
    @abstractmethod
    def embed(self, texts, prefix=None):
        ...
