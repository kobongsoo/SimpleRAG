from abc import ABC, abstractmethod


class GenerateError(Exception):
    """생성 단계에서 복구 불가능한 오류(모델 없음, 로딩 실패 등)."""


class Generator(ABC):
    #------------------------------------------------------------------
    # 모델 적재 보장 (지연 로딩)
    # -out: load_ms
    #------------------------------------------------------------------
    @abstractmethod
    def ensure_loaded(self):
        ...

    #------------------------------------------------------------------
    # 로드 여부
    #------------------------------------------------------------------
    @abstractmethod
    def is_ready(self):
        ...

    #------------------------------------------------------------------
    # 스트리밍 생성
    # -out: Iterator[str]
    #------------------------------------------------------------------
    @abstractmethod
    def stream(self, query, chunks, max_tokens=None, system=None):
        ...
