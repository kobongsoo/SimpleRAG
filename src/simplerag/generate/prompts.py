#------------------------------------------------------------------
# 지금 설정의 시스템 지시문
#=> 생성기가 system 인자를 받지 않았을 때 쓸 지시문을 설정(config.PROMPT)에서 고른다.
#   예열(warm)도 같은 경로를 타므로, 바꾼 지시문의 KV 도 미리 만들어진다.
#    1) custom 이면 config.yaml generation.system_prompt 글을 그대로 쓴다
#    2) 그 밖에는 PROMPTS 에 미리 적어 둔 v0 | v4 | v5 중 하나
#
# -in: name = 프롬프트 이름(None 이면 config.PROMPT)
#
# -out: 지시문 문자열
# -out: error = 모르는 이름이면 ValueError, custom 인데 글이 비었으면 ValueError
#               (설정 검증을 통과했다면 둘 다 일어나지 않는다)
#------------------------------------------------------------------
def active_system_prompt(name=None):
    key = (name or config.PROMPT or "v0").strip().lower()
    if key == "custom":
        # 사용자가 config.yaml 에 직접 쓴 지시문 — 비어 있으면 지시 없이 답하게 되므로 막는다
        if not config.SYSTEM_PROMPT_TEXT:
            raise ValueError("prompt: custom 인데 generation.system_prompt 가 비어 있습니다")
        return config.SYSTEM_PROMPT_TEXT
    if key not in PROMPTS:
        raise ValueError("알 수 없는 프롬프트 '{}' — {} 중 하나".format(key, " | ".join(PROMPTS)))
    return PROMPTS[key]


#------------------------------------------------------------------
# 사용자 메시지 조립
#=> [근거] 블록 + [질문] 형태. 근거에 번호를 매겨 모델이 출처를 표기할 수 있게 한다.
#
# -in: query  = 사용자 질문
# -in: chunks = 검색된 청크 텍스트 목록(순위 순)
#
# -out: user_msg = 사용자 메시지 본문
#------------------------------------------------------------------
def build_user_message(query, chunks):
    # 표가 든 근거는 "머리글: 값" 행 평문으로 펴서 넣는다(계획서 3-3).
    #   색인은 건드리지 않고 모델에 보여 줄 때만 바꾸므로 검색 결과는 그대로다.
    if config.FLATTEN_TABLES:
        from ..tableflat import flatten_tables
        chunks = [flatten_tables(c) for c in chunks]
    blocks = ["[{}] {}".format(i + 1, c) for i, c in enumerate(chunks)]
    return "[근거]\n" + "\n\n".join(blocks) + "\n\n[질문]\n" + query


#------------------------------------------------------------------
# Qwen3 채팅 프롬프트 조립 (thinking 비활성) — 핵심
#=> Qwen3 는 thinking 모드가 켜지면 사고토큰 수백 개를 먼저 생성해 약 3배
#   느려진다. <think> 블록을 미리 닫아 두면 바로 답변을 시작한다.
#   (템플릿에서 enable_thinking=False 일 때와 같은 형태)
#
# -in: system = 시스템 지시문
# -in: user   = 사용자 메시지
#
# -out: prompt = 모델에 그대로 넣을 완성 문자열
#------------------------------------------------------------------
def build_prompt(system, user):
    return (
        "<|im_start|>system\n" + system + "<|im_end|>\n"
        "<|im_start|>user\n" + user + "<|im_end|>\n"
        "<|im_start|>assistant\n<think>\n\n</think>\n\n"
    )


#------------------------------------------------------------------
# 지시문 되뱉기 제거 — 소형 모델 특유의 잡음
#=> 0.6B 는 시스템 지시문의 문구를 답변 안에 그대로 옮겨 적는 일이 있다.
#   실측 45문항 중 4건에서 관찰됐다.
#     "리프레시 휴가비는 … 지급합니다. [1] 근거 번호 [1] 형식으로 표기합니다."
#     "본인 결혼 시 경조 휴가는 … 계산됩니다. [1] 형식으로 답변합니다. [1]"
#
#   ⚠️ 이것은 **표시 품질** 교정이지 정답률 교정이 아니다. 누출이 있던 4건은
#      되뱉기를 지우더라도 숫자 자체가 틀려서 어차피 오답이다(REPORT §18).
#      "형식 잡음만 걷어내면 점수가 오른다"고 기대하면 안 된다.
#
#   프롬프트 문구를 고치지 않고 후처리로 지운다 — 문구를 바꾸면 생성 결과가
#   통째로 달라져 재측정이 필요하고, V3 전례처럼 역전될 수 있다(설계서 R9).
#------------------------------------------------------------------
_ECHO_PATTERNS = (
    # "[1] 형식으로 표기합니다" / "근거 번호를 [3] 형식으로 답변합니다"
    #   / "[1] 형식으로 근거 번호 표기." — 낱말 순서를 뒤집어 옮겨 적는 경우도 있다(506문항)
    re.compile(r"(?:근거\s*번호를?\s*)?\[\d+\]\s*형식으로\s*(?:근거\s*번호\s*)?"
               r"(?:표기|표시|답변|작성|기재)[가-힣]*\.?"),
    # "답변은 3~5문장으로 요약하고"
    re.compile(r"답변은\s*\d+\s*[~\-]\s*\d+\s*문장으로\s*요약[가-힣]*\.?"),
    # "근거에 없는 내용은 추측하지 마세요"
    re.compile(r"근거에\s*없는\s*내용은\s*추측하지\s*마(?:세요|십시오)\.?"),
    # 인용 앞에 붙는 군더더기 — "[1] 근거 번호 [1]" → "[1] [1]"
    re.compile(r"근거\s*(?:번호를?)?\s*(?=\[\d+\])"),

    # ── 계획서 1-4(REPORT §45)에서 보탠 것 — 실제 수집 답변에서 센 것만 넣는다 ──
    # "근거 번호: [1]" — 위 패턴은 콜론이 끼면 못 잡는다
    re.compile(r"근거\s*번호\s*[:：]\s*(?=\[\d+\])"),
    # "[3] 번의 근거 번호는 [3]입니다" / "[1]의 근거 번호는 [1]이다"
    re.compile(r"\[?\d+\]?\s*번?\s*의?\s*근거\s*번호는\s*\[?\d+\]?\s*(?:입니다|이다)\.?"),
    # "…[1] 근거 번호입니다"
    re.compile(r"근거\s*번호(?:입니다|이다)\.?"),
    # "근거에 없는 내용은 추측하지 않습니다 / 않아, …" — 지시문을 평서문으로 바꿔 옮겨 적는다
    re.compile(r"근거에\s*없는\s*내용은\s*추측하지\s*(?:않습니다|않았습니다|않으며|않고|않아)[,，]?\s*"),
    # "[1]번으로 간결하게 답변합니다" / "[1]과 [2]의 정보를 바탕으로 답변합니다"
    #   — 앞 40자 안에 지시문 낱말(간결하게·바탕으로·참고하여·근거로)이 있을 때만 지운다.
    #     그냥 "답변합니다" 로 끝나는 정상 문장은 건드리지 않는다.
    re.compile(r"[^.\n]{0,40}(?:간결하게|바탕으로|참고하여|근거로)\s*답변(?:합니다|드립니다|하겠습니다)\.?"),
    # "[1] 번호 [1]로 답변합니다" — 위 40자 규칙의 낱말 목록에 없는 변형(506문항)
    #   앞에 한글이 붙은 "전화번호 [1]로 답변합니다" 같은 정상 문장은 건드리지 않는다.
    re.compile(r"(?<![가-힣])번호\s*\[?\d+\]?\s*로\s*답변(?:합니다|드립니다|하겠습니다)\.?"),
    # 인용 자리에 지시문을 통째로 넣은 것 — "[근거 번호 1]" (진짜 인용 "[1]" 은 건드리지 않는다)
    re.compile(r"\[\s*근거\s*번호\s*\d+\s*\]"),
    # 본문 중간으로 옮겨 적은 블록 표식 — "[근거]" / "[질문]" (첫머리는 _LEADING_MARKER 가 잡는다)
    re.compile(r"\[(?:근거|질문)\]\s*"),
)

# 마크다운 굵게 — 콘솔에는 별표가 그대로 보인다("**DELL P2422H**"). 1.7B 가 특히 자주 쓴다
#   (골든셋 100문항에서 0.6B 8건 · 1.7B 18건). 글자는 남기고 별표만 벗긴다.
_MD_BOLD = re.compile(r"\*\*(.+?)\*\*", re.S)
_MD_STRAY = re.compile(r"\*{2,}")

# 사용자 메시지의 블록 표식을 답변 첫머리에 그대로 옮겨 적는 경우.
_LEADING_MARKER = re.compile(r"^\s*\[(?:질문|근거)\]\s*")

# 끝에 달라붙는 중복 인용 — "[3]번 [3]", "[1] [1]" 처럼 같은 번호를 반복한다.
_TRAILING_CITES = re.compile(r"(?:\s*\[\d+\]\s*번?)+\s*$")

# ── 짧은 되뱉기 (거르기 켬·끔과 상관없이 지운다 — 설계서 ②③) ──────────────
#   모양이 고정된 짧은 잡음이라 몇 글자만 붙들면 판정된다(긴 _ECHO_PATTERNS 는 앞 40자까지
#   지워야 해서 첫 문장을 통째로 붙들어야 했다). 골든셋 100문항(1.7B, 거르기 끔)에서 남은 9건:
#     "근거 [1]에 따르면" 5건 · "근거 번호: [2]" · "[1] 형식으로 표기:" · "[1]의 근거 번호는 [1]입니다" ·
#     끝 인용 두 번 찍기 "[1][3][1][3]"
#   _SHORT_LIVE 는 스트리밍 중(끝맺음이 와야 지움), _SHORT_FINAL 은 답이 끝난 뒤(글 끝도 끝맺음).
_SHORT_COMMON = (
    re.compile(r"\[\d+\]\s*의\s*근거\s*번호는\s*\[\d+\]\s*입니다\.?"),
    re.compile(r"근거\s*번호\s*:?\s*\[\d+\]"),
    # 낱말 '근거' 뒤에 바로 인용 번호가 올 때만 — "근거 규정은 …" 같은 본문은 건드리지 않는다
    re.compile(r"(?<![가-힣])근거\s*(?=\[\d+\])"),
)
_SHORT_FORMAT_LIVE = re.compile(r"(?:근거\s*번호\s*)?\[\d+\]\s*형식으로\s*(?:근거\s*번호를?\s*)?표기[^.\n:]*[.:]")
_SHORT_FORMAT_FINAL = re.compile(r"(?:근거\s*번호\s*)?\[\d+\]\s*형식으로\s*(?:근거\s*번호를?\s*)?표기[^.\n:]*(?:[.:]|$)")
# 인용 덩어리가 곧바로 한 번 더 — "[1][3][1][3]" → "[1][3]"
_DUP_CITE_RUN = re.compile(r"(\[\d+\](?:\s*\[\d+\])*)\s*\1(?!\d)")
# 붙들기 판정용 정규형(숫자→1, 공백·쌍점 제거)으로 적은 짧은 되뱉기 — 꼬리가 이것들의 앞부분이면 붙든다
_SHORT_CANON = ("[1]의근거번호는[1]입니다", "[1]형식으로표기", "[1]형식으로근거번호표기", "[1]형식으로근거번호를표기",
                "근거번호[1]형식으로표기", "근거번호[1]", "근거[1]")
_FORMAT_CANON = ("[1]형식으로표기", "[1]형식으로근거번호표기", "[1]형식으로근거번호를표기", "근거번호[1]형식으로표기")
_CANON_LEAD_RUN = re.compile(r"(?:\[1\])*")
_CANON_RUN = re.compile(r"(?:\[1\])*(?:\[1?)?")


