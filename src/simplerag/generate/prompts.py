# 프롬프트 조립 + 출력 파싱 (설계서 결정7 / 결정2)
#=> RAG 생성 단계의 '문자열 계약'을 한 곳에 모은다.
#
#   ⚠️ 프롬프트를 바꾸려면 반드시 실코퍼스 평가셋으로 재측정할 것(설계서 R9).
#   초안은 인용 강제형(V3)을 썼다가 실문서에서 정답률이 83%→50% 로 무너져
#   폐기했다. 합성 데이터로 튜닝한 프롬프트는 실데이터에서 역전될 수 있다.
#------------------------------------------------------------------

import re

from .. import config

# 채택 프롬프트(V0). 단순 지시가 실문서에서 가장 좋았다.
#   - 실문서 기준 정답률 83%(0.6B) / 92%(1.7B), 혼동률 0%
#   - "근거 중 하나만 골라라" 류의 선택 지시는 0.6B 에 해롭다(엉뚱한 조문 인용)
SYSTEM_PROMPT = (
    "당신은 사내 문서 검색 도우미입니다. 아래 [근거] 안의 내용만 사용해 한국어로 "
    "간결하게 답변하세요. 근거에 없는 내용은 추측하지 마세요. "
    "답변은 3~5문장으로 요약하고 마지막에 근거 번호를 [1] 형식으로 표기하세요."
)

# 실험 프롬프트(V4) — 계획서 1-3 / REPORT §40. 🔴 기각(2026-09-15): 506문항 377→358(잃음 30/얻음 11,
#   p=0.004), 골든셋 F·AR 잡음 이내·핵심어 39→32. 짧게 쓰게 하자 틀린 말이 아니라 맞는 두 번째 사실이
#   빠졌다. 재현용으로만 남긴다 — 기본값(v0)을 바꾸지 말 것.
#   V0 에서 "3~5문장으로 요약" 한 곳만 바꿨다: 질문의 답을 첫 문장에 바로 쓰고 1~2문장으로.
#   §36 에서 긴 답의 F 가 낮았고(0.622 vs 0.719), §39 에서 끝을 잘라도 그대로였다 — 문제는
#   길이가 아니라 "요약하라" 는 지시가 근거를 옮겨 적으며 문장을 늘리는 쪽이라는 가설.
#   나머지 문구(추측 금지·인용 표기)는 **글자 그대로** 둔다 — 되뱉기 제거 패턴(_ECHO_PATTERNS)이
#   V0 문구에 맞춰져 있고, 문구를 여러 곳 바꾸면 무엇이 효과였는지 가를 수 없다(V3 전례, §13.5).
#   "답변은 1~2문장으로 요약" 도 기존 되뱉기 패턴에 걸리는 모양으로 맞췄다.
SYSTEM_PROMPT_V4 = (
    "당신은 사내 문서 검색 도우미입니다. 아래 [근거] 안의 내용만 사용해 한국어로 "
    "간결하게 답변하세요. 근거에 없는 내용은 추측하지 마세요. "
    "질문에 대한 답을 첫 문장에 바로 쓰고, 답변은 1~2문장으로 요약하고 "
    "마지막에 근거 번호를 [1] 형식으로 표기하세요."
)

# 설정 이름 → 지시문. config.yaml generation.prompt / 환경변수 SIMPLERAG_PROMPT 로 고른다.
PROMPTS = {"v0": SYSTEM_PROMPT, "v4": SYSTEM_PROMPT_V4}


#------------------------------------------------------------------
# 지금 설정의 시스템 지시문
#=> 생성기가 system 인자를 받지 않았을 때 쓸 지시문을 설정(config.PROMPT)에서 고른다.
#   예열(warm)도 같은 경로를 타므로, 바꾼 지시문의 KV 도 미리 만들어진다.
#
# -in: name = 프롬프트 이름(None 이면 config.PROMPT)
#
# -out: 지시문 문자열
# -out: error = 모르는 이름이면 ValueError (설정 검증을 통과했다면 일어나지 않는다)
#------------------------------------------------------------------
def active_system_prompt(name=None):
    key = (name or config.PROMPT or "v0").strip().lower()
    if key not in PROMPTS:
        raise ValueError("알 수 없는 프롬프트 '{}' — {} 중 하나".format(key, " | ".join(PROMPTS)))
    return PROMPTS[key]


#------------------------------------------------------------------
# 사용자 메시지 조립
#=> [근거] 블록 + [질문] 형태. 근거에 번호를 매겨 모델이 출처를 표기할 수 있게 한다.
#
# -in: query  = 사용자 질문
# -in: chunks = 검색된 청크 텍스트 목록(순위 순)
#
# -out: user_msg = 사용자 메시지 본문
#------------------------------------------------------------------
def build_user_message(query, chunks):
    blocks = ["[{}] {}".format(i + 1, c) for i, c in enumerate(chunks)]
    return "[근거]\n" + "\n\n".join(blocks) + "\n\n[질문]\n" + query


#------------------------------------------------------------------
# Qwen3 채팅 프롬프트 조립 (thinking 비활성) — 핵심
#=> Qwen3 는 thinking 모드가 켜지면 사고토큰 수백 개를 먼저 생성해 약 3배
#   느려진다. <think> 블록을 미리 닫아 두면 바로 답변을 시작한다.
#   (템플릿에서 enable_thinking=False 일 때와 같은 형태)
#
# -in: system = 시스템 지시문
# -in: user   = 사용자 메시지
#
# -out: prompt = 모델에 그대로 넣을 완성 문자열
#------------------------------------------------------------------
def build_prompt(system, user):
    return (
        "<|im_start|>system\n" + system + "<|im_end|>\n"
        "<|im_start|>user\n" + user + "<|im_end|>\n"
        "<|im_start|>assistant\n<think>\n\n</think>\n\n"
    )


#------------------------------------------------------------------
# 지시문 되뱉기 제거 — 소형 모델 특유의 잡음
#=> 0.6B 는 시스템 지시문의 문구를 답변 안에 그대로 옮겨 적는 일이 있다.
#   실측 45문항 중 4건에서 관찰됐다.
#     "리프레시 휴가비는 … 지급합니다. [1] 근거 번호 [1] 형식으로 표기합니다."
#     "본인 결혼 시 경조 휴가는 … 계산됩니다. [1] 형식으로 답변합니다. [1]"
#
#   ⚠️ 이것은 **표시 품질** 교정이지 정답률 교정이 아니다. 누출이 있던 4건은
#      되뱉기를 지우더라도 숫자 자체가 틀려서 어차피 오답이다(REPORT §18).
#      "형식 잡음만 걷어내면 점수가 오른다"고 기대하면 안 된다.
#
#   프롬프트 문구를 고치지 않고 후처리로 지운다 — 문구를 바꾸면 생성 결과가
#   통째로 달라져 재측정이 필요하고, V3 전례처럼 역전될 수 있다(설계서 R9).
#------------------------------------------------------------------
_ECHO_PATTERNS = (
    # "[1] 형식으로 표기합니다" / "근거 번호를 [3] 형식으로 답변합니다"
    re.compile(r"(?:근거\s*번호를?\s*)?\[\d+\]\s*형식으로\s*"
               r"(?:표기|표시|답변|작성|기재)[가-힣]*\.?"),
    # "답변은 3~5문장으로 요약하고"
    re.compile(r"답변은\s*\d+\s*[~\-]\s*\d+\s*문장으로\s*요약[가-힣]*\.?"),
    # "근거에 없는 내용은 추측하지 마세요"
    re.compile(r"근거에\s*없는\s*내용은\s*추측하지\s*마(?:세요|십시오)\.?"),
    # 인용 앞에 붙는 군더더기 — "[1] 근거 번호 [1]" → "[1] [1]"
    re.compile(r"근거\s*(?:번호를?)?\s*(?=\[\d+\])"),
)

# 사용자 메시지의 블록 표식을 답변 첫머리에 그대로 옮겨 적는 경우.
_LEADING_MARKER = re.compile(r"^\s*\[(?:질문|근거)\]\s*")

# 끝에 달라붙는 중복 인용 — "[3]번 [3]", "[1] [1]" 처럼 같은 번호를 반복한다.
_TRAILING_CITES = re.compile(r"(?:\s*\[\d+\]\s*번?)+\s*$")


#------------------------------------------------------------------
# 실재하지 않는 인용 번호 제거 (핵심 — 구조 인식 청킹의 부작용)
#=> 근거가 3건인데 답변에 `[12]` 가 달리는 일이 있다. 실제 관측된 원문:
#
#     [1] 원격지 근무자에게는 숙박비, 운임, … 지급한다.
#     [2] 원격지 근무자에게는 숙박비, 운임, … 지급한다.
#     [12] 원격지 근무자 비품 구매 관련 지침_22.01.25 > 1. 대상자
#      ^^^^ 근거는 3건뿐인데 12번을 인용했다
#
#   🔴 원인은 **대괄호 표기가 겹치는 것**이다. 구조 인식 청킹이 청크 앞에
#      `[문서명 > 절제목]` 접두를 붙이는데, 문서명이 번호로 시작하는 일이 잦다.
#
#        근거 3번의 접두 : [12.원격지 근무자 비품 구매 관련 지침_22.01.25]
#        인용 표기 규약  : [1] [2] [3]
#
#      모델 눈에는 둘이 같은 모양이라, 접두를 따라 쓰면서 `[12]` 를 인용처럼
#      찍어 버린다. 고정 청킹 때는 접두가 없어 드러나지 않던 결함이다.
#
#   근본 해결은 접두의 괄호 모양을 바꾸는 것이지만, 그러면 색인된 텍스트가
#   달라져 **전체 재인덱싱과 재측정**이 필요하다. 여기서는 출력만 고친다 —
#   근거 개수를 넘는 번호는 가리키는 곳이 없으므로 인용이 아니다.
#
#   ⚠️ 본문에서도 손본다. 화면에 `[12]` 가 남으면 없는 근거를 가리키는
#      셈이라, 목록에서만 빼는 것으로는 부족하다.
#
#   🔴 그런데 **지우면 안 된다.** 대괄호 안의 숫자가 인용이 아니라 **값**인
#      경우가 있다. 204문항 실측에서 나왔다.
#
#        "사업예산은 [1]에 따르면, [75]억 원입니다."
#                                  ^^^^ 인용이 아니라 금액이다
#
#      지우면 "억 원입니다" 가 되어 **숫자가 사라진다.** 범위 밖 숫자 5건을
#      살펴보니 4건은 헛인용이고 1건은 이렇게 값이었다.
#
#      → **괄호만 벗기고 숫자는 남긴다.** 헛인용이면 군더더기 숫자가 하나
#         남을 뿐이지만(`[5] [결혼퇴직]` → `5 [결혼퇴직]`), 값이면 내용이
#         보존된다(`[75]억` → `75억`). 잃는 쪽이 얻는 쪽보다 훨씬 나쁘다.
#         괄호가 사라지므로 인용으로 읽히는 일은 어느 쪽이든 없어진다.
#
# -in: body       = 본문
# -in: n_evidence = 실제 근거 개수. None 이면 아무것도 건드리지 않는다
#                   (개수를 모르면 판단할 수 없으므로 보존이 안전하다)
#
# -out: 유효 범위(1~n) 밖의 [숫자] 에서 괄호를 벗긴 본문
# -out: error = 없음
#------------------------------------------------------------------
def drop_invalid_cites(body, n_evidence=None):
    if not n_evidence or not body:
        return body

    def keep(m):
        n = int(m.group(1))
        # 유효 범위면 그대로, 아니면 괄호만 벗긴다(숫자는 절대 버리지 않는다).
        return m.group(0) if 1 <= n <= n_evidence else m.group(1)

    return re.sub(r"\[(\d+)\]", keep, body)


#------------------------------------------------------------------
# 되뱉기·중복인용 정리
#=> 지시문 되뱉기를 지우고, 끝에 반복된 인용 번호를 하나로 접는다.
#   인용 번호 자체는 보존한다(순서 유지, 중복만 제거).
#
# -in: body       = 파싱된 본문
# -in: n_evidence = 근거 개수. 주면 실재하지 않는 인용 번호도 함께 지운다
#
# -out: 정리된 본문
#------------------------------------------------------------------
def strip_instruction_echo(body, n_evidence=None):
    cleaned = _LEADING_MARKER.sub("", body)
    for pat in _ECHO_PATTERNS:
        cleaned = pat.sub(" ", cleaned)

    # 되뱉기 패턴이 `[1] 형식으로 표기` 처럼 번호를 포함하므로, 번호를
    # 지우는 것은 되뱉기 제거가 끝난 뒤여야 한다(먼저 지우면 매칭이 깨진다).
    cleaned = drop_invalid_cites(cleaned, n_evidence)

    m = _TRAILING_CITES.search(cleaned)
    if m:
        seen, uniq = set(), []
        for n in re.findall(r"\[(\d+)\]", m.group(0)):
            if n not in seen:
                seen.add(n)
                uniq.append(n)
        cleaned = cleaned[:m.start()] + " " + "".join(
            "[{}]".format(n) for n in uniq)

    cleaned = re.sub(r"\s+", " ", cleaned).strip()
    cleaned = re.sub(r"\s+([.,])", r"\1", cleaned)
    # 되뱉기만 남고 본문이 사라지면 원문을 돌려준다(과잉 삭제 방지).
    return cleaned if cleaned.strip(" .[]0123456789") else body


#------------------------------------------------------------------
# 출력 파싱 (3단계 폴백)
#=> 모델이 형식을 지키지 않는 경우가 있어 순서대로 물러선다.
#    1) '답변:' 이후를 본문으로
#    2) 없으면 '인용:' 이후를 본문으로 (인용문 자체가 답을 담고 있음)
#    3) 둘 다 없으면 전체 텍스트
#   V0 는 이런 머리말을 요구하지 않지만, 모델이 제멋대로 붙이는 일이 있어
#   방어적으로 유지한다.
#
# -in: text       = 모델 원문 출력
# -in: n_evidence = 실제 근거 개수. 주면 그 범위를 벗어난 인용을 버린다
#                   (근거 3건에 `[12]` 가 달리는 결함 — drop_invalid_cites 참조)
#
# -out: (body, cited) = 본문, 인용된 근거 번호 목록(예: [1, 3])
#------------------------------------------------------------------
def parse_answer(text, n_evidence=None):
    body = (text or "").strip()

    for marker in ("답변:", "인용:"):
        if marker in body:
            body = body.split(marker, 1)[1].strip()
            break

    body = strip_instruction_echo(body, n_evidence)

    cited = sorted({int(n) for n in re.findall(r"\[(\d+)\]", body)})
    # 본문 정리가 실패해도 목록에는 없는 번호가 새지 않도록 한 번 더 거른다.
    if n_evidence:
        cited = [n for n in cited if 1 <= n <= n_evidence]
    return body, cited
