#------------------------------------------------------------------
# 표 행렬 도우미 (재설계서 §6 · §10)
#=> 포맷마다 표를 저장하는 방식(병합 표기·셀 주소)은 다르지만, 결과는 모두
#   "행 × 열 글자 행렬"로 맞춘다. 병합 셀 펼치기, 빈 줄·빈 열 다듬기, 머리글 행 추정,
#   마크다운 표 줄 렌더링을 여기 한곳에 모아 포맷별 추출기가 같은 규칙을 쓰게 한다.
#------------------------------------------------------------------

import re

# 숫자만 든 칸(금액·일수·날짜). 머리글 판정에 쓴다 — 머리글 칸은 이름표라 숫자가 아니다.
_NUMERIC = re.compile(r"[-\d,.\s%/:()~]*\d[-\d,.\s%/:()~]*")


#------------------------------------------------------------------
# 셀 글자 다듬기
#=> 셀 안의 줄바꿈·탭·연속 공백을 공백 하나로 합친다. 표 한 행이 한 줄이어야
#   "| a | b |" 렌더링과 머리글 재부착이 성립한다. 파이프 문자는 칸 구분자와
#   헷갈리므로 전각 '｜' 로 바꾼다.
#
# -in: s = 셀 원문
#
# -out: str = 한 줄로 다듬은 셀 글자
# -out: error = 없음
#------------------------------------------------------------------
def clean_cell(s):
    s = " ".join((s or "").split())
    # 칸 구분자와 겹치지 않게 — 렌더링된 줄을 다시 쪼갤 때 칸이 늘어나는 것을 막는다
    return s.replace("|", "｜")


#------------------------------------------------------------------
# 빈 격자 만들기
#=> 병합 정보를 반영해 셀을 채워 넣을 자리를 미리 만든다.
#
# -in: n_rows = 행 수
# -in: n_cols = 열 수
#
# -out: grid = [[None, …], …] — None 은 아직 채워지지 않은 칸
# -out: error = 없음
#------------------------------------------------------------------
def new_grid(n_rows, n_cols):
    return [[None] * max(0, n_cols) for _ in range(max(0, n_rows))]


#------------------------------------------------------------------
# 격자에 셀 하나 놓기 (병합 펼치기)
#=> 병합 셀은 아래 규칙으로 펼친다.
#    1) 세로 병합(rowspan) — 아래 행들에 **같은 글자를 되풀이**한다.
#       행마다 이름표가 있어야 "5 가 일수인지 금액인지"를 행 단독으로 알 수 있다.
#    2) 가로 병합(colspan) — 첫 칸에만 글자를 두고 나머지는 빈칸으로 둔다.
#       전체 폭 제목 행이 "| 출장여비 | 출장여비 | 출장여비 |" 로 부풀어
#       토큰을 낭비하는 것을 막는다.
#   격자 밖으로 나가는 부분은 조용히 잘라 낸다(주소가 깨진 파일 방어).
#
# -in: grid = new_grid() 결과(제자리 수정)
# -in: r, c = 시작 행·열(0부터)
# -in: text = 셀 글자
# -in: rowspan, colspan = 병합 크기(기본 1)
#
# -out: 없음
# -out: error = 없음 (범위를 벗어나면 그 부분만 버린다)
#------------------------------------------------------------------
def place(grid, r, c, text, rowspan=1, colspan=1):
    rowspan = max(1, rowspan or 1)
    colspan = max(1, colspan or 1)
    for dr in range(rowspan):
        rr = r + dr
        if rr < 0 or rr >= len(grid):
            continue
        for dc in range(colspan):
            cc = c + dc
            if cc < 0 or cc >= len(grid[rr]):
                continue
            # 가로로는 첫 칸만, 세로로는 모든 행의 첫 칸에 글자를 둔다
            grid[rr][cc] = text if dc == 0 else ""


#------------------------------------------------------------------
# 격자 → 행 목록 (다듬기)
#=> None 칸을 빈칸으로 바꾸고, 완전히 빈 행·빈 열을 걷어 낸다.
#   셀 안의 줄바꿈은 **그대로 둔다** — 한 칸짜리 표(글상자로 쓴 표)를 문단으로
#   되돌릴 때 줄 구분이 필요하다. 한 줄로 다듬는 일은 postprocess 가 한다.
#
# -in: grid = 채워진 격자
#
# -out: rows = [[셀, …], …] — 내용이 없으면 []
# -out: error = 없음
#------------------------------------------------------------------
def finish(grid):
    rows = [[(x or "").strip() for x in row] for row in grid]
    rows = [row for row in rows if any(row)]
    if not rows:
        return []
    width = max(len(row) for row in rows)
    rows = [row + [""] * (width - len(row)) for row in rows]
    # 모든 행에서 빈 열은 장식용 칸이다 — 남겨 두면 "| a | | b |" 처럼 칸이 밀려 보인다
    keep = [j for j in range(width) if any(row[j] for row in rows)]
    return [[row[j] for j in keep] for row in rows]


#------------------------------------------------------------------
# 숫자 칸인가
#
# -in: cell = 셀 글자
#
# -out: bool = 숫자(와 단위 기호)만으로 이뤄졌으면 True
# -out: error = 없음
#------------------------------------------------------------------
def _is_number(cell):
    return bool(cell) and bool(_NUMERIC.fullmatch(cell))


#------------------------------------------------------------------
# 머리글 행처럼 보이는가
#=> 이름표 칸이 2개 이상이고 숫자 칸이 하나도 없으면 머리글로 본다
#   (structure._looks_like_header 와 같은 기준).
#
# -in: row = 셀 목록
#
# -out: bool
# -out: error = 없음
#------------------------------------------------------------------
def looks_like_header(row):
    named = [c for c in row if c]
    if len(named) < 2:
        return False
    return not any(_is_number(c) for c in named)


#------------------------------------------------------------------
# 머리글 행 수 정하기
#=> 파일이 머리글을 표시했으면(DOCX tblHeader · HWPX header 속성) 그 값을 쓰고,
#   없으면 첫 행이 머리글처럼 생겼을 때만 1 로 본다. 값 행을 머리글로 잘못 잡으면
#   뒤따르는 조각마다 엉뚱한 이름표가 붙으므로 모르면 0 이 안전하다.
#
# -in: rows     = 행 목록
# -in: declared = 파일이 표시한 머리글 행 수(없으면 0)
#
# -out: int = 머리글 행 수
# -out: error = 없음
#------------------------------------------------------------------
def header_rows(rows, declared=0):
    if declared:
        # 표 전체가 머리글로 표시된 경우(양식 표)는 머리글이 없는 것과 같다
        return declared if declared < len(rows) else 0
    return 1 if rows and len(rows) > 1 and looks_like_header(rows[0]) else 0


#------------------------------------------------------------------
# 행 하나를 마크다운 표 줄로
#
# -in: row = 셀 목록
#
# -out: str = "| a | b |"
# -out: error = 없음
#------------------------------------------------------------------
def render_row(row):
    return "| " + " | ".join(row) + " |"


#------------------------------------------------------------------
# 표 전체를 마크다운 표 줄로
#=> 기존 normalize_tables 의 결과와 같은 모양이라 생성 단계의 tableflat
#   ("머리글: 값" 평문화)이 그대로 동작한다.
#
# -in: rows = 행 목록
#
# -out: str = 줄바꿈으로 이은 표 줄
# -out: error = 없음
#------------------------------------------------------------------
def render(rows):
    return "\n".join(render_row(r) for r in rows)
