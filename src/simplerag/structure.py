#------------------------------------------------------------------
# 문서 구조 인식 (plan/구조인식_청킹_설계.md)
#=> 고정 크기 청킹은 문서 구조를 전혀 보지 않는다. 실측 결과 회사규정
#   조문 123개 중 **89개(72%)가 청크 경계에 걸려** 두 조각으로 나뉘어 있었다.
#   검색이 그중 한쪽만 가져오면 모델은 조문의 절반만 보고 답한다.
#
#   이 모듈은 '어디서 자르면 안 되는가'를 알려 준다. 자르는 일 자체는
#   chunk.py 가 한다.
#
#   설계 판단 두 가지
#     ① 크기를 키우지 않는다. §17 에서 128/192/256 을 전수 비교한 결과
#        정답률은 평평하고 TTFT 만 컨텍스트 길이에 비례해 늘었다.
#        필요한 것은 '크게 자르는 것'이 아니라 '경계를 지키는 것'이다.
#     ② 조문 문법만 보면 실패한다. 코퍼스 표본 77건에서 `제N조` 를 가진
#        문서는 **6%** 뿐이었다(번호절 38% · 표 25% · 마크다운 19%).
#        회사규정 18건으로 좁혀도 조문 보유는 6건(33%)이다.
#        → 문법 다중화와 폴백이 이 모듈의 본체다.
#------------------------------------------------------------------

import re

# ── 제목 문법 ────────────────────────────────────────
# 우선순위대로 나열한다. **문서마다 하나만** 채택한다(아래 detect_grammar 참조).
_GRAMMARS = [
    # 제5조(지급 금액) / 제 5 조 【 시행일 】
    ("조문", re.compile(r"^[ \t]*제\s*\d+\s*조\s*[(【][^\n]{0,60}?[)】][ \t]*$|"
                        r"^[ \t]*제\s*\d+\s*조[ \t][^\n]{0,60}$", re.M)),
    # ## 제목  (마크다운)
    ("마크다운", re.compile(r"^[ \t]*#{1,6}[ \t]+\S[^\n]*$", re.M)),
    # 1. 적용대상 / 1.2 정의 / 14.1 동호회는 …
    ("번호절", re.compile(r"^[ \t]*\d+(?:\.\d+)*\.?[ \t]+\S[^\n]{0,80}$", re.M)),
]

_MIN_HEADINGS = 3          # 이만큼 나와야 '구조가 있다'고 본다
_TABLE_LINE = re.compile(r"^[ \t]*\|.*\|[ \t]*$")

#------------------------------------------------------------------
# 부속서 표지 — 문법과 별개로 **항상** 절 경계로 본다
#=> `별표1`·`[붙임 2]`·`(별첨 #1)`·`부칙` 은 본문 조문 안에 나타나지 않는
#   최상위 구분이다. 그래서 조문/번호절 중 무엇을 채택했든 함께 경계로 쓴다.
#   문법 하나만 고르는 원칙(detect_grammar)과 충돌하지 않는다 — 조문을 잘게
#   부수는 것은 조문의 '하위' 항목이지 이런 최상위 표지가 아니다.
#
#   🔴 같은 표지가 **참조로도** 쓰인다. 이 둘을 갈라야 한다.
#       별표1                     국내출장여비      ← 제목 (경계)
#       별표1에 따라 지급한다.                       ← 참조 (경계 아님)
#   번호 뒤에 조사가 바로 붙으면 참조다.
#
#   실측(367건): 별표 6건 · 별첨 7건 · 붙임 8건 · 참고 6건 · 서식 3건 ·
#   부록 1건 · 부칙 22건
#------------------------------------------------------------------
_APPENDIX = re.compile(
    r"^[ \t]*[\[(]?\s*"
    r"(?:별\s*표|별\s*첨|붙\s*임|참\s*고|서\s*식|부\s*록|첨\s*부)"
    r"\s*#?\s*[\dA-Z]+(?![가-힣])[^\n]*$"
    r"|^[ \t]*부\s*칙(?![가-힣])[^\n]*$", re.M)
_MIN_APPENDIX = 2          # 부속서만 있는 문서도 살린다(표지가 명확하므로)


#------------------------------------------------------------------
# 제목 문법 감지 (핵심)
#=> 문서 전체를 훑어 **가장 우선순위 높은 문법 하나만** 고른다.
#
#   🔴 하나만 고르는 것이 핵심이다. 조문 문서 안의 `1.` `2.` 는 조문의
#      하위 항목이지 절이 아니다. 둘을 함께 경계로 쓰면 조문이 오히려 더
#      잘게 부서진다 — 실측에서 취업규칙이 조문 77개 대신 절 119개로
#      쪼개졌다.
#
# -in: text = 문서 본문
#
# -out: (이름, 정규식) 또는 (None, None) — 구조가 없으면 고정 크기로 폴백
#------------------------------------------------------------------
def detect_grammar(text):
    for name, pat in _GRAMMARS:
        if len(pat.findall(text)) >= _MIN_HEADINGS:
            return name, pat
    return None, None


#------------------------------------------------------------------
# 절 분할
#=> 제목 위치에서만 끊는다. 길이는 보지 않는다(패킹 단계의 일이다).
#   첫 제목 앞의 머리말(제목·제정일 등)도 하나의 절로 살린다.
#
# -in: text = 문서 본문
#
# -out: [(제목, 절 본문), ...] — 구조가 없으면 [(None, 전체)]
#------------------------------------------------------------------
def split_sections(text):
    name, pat = detect_grammar(text)

    # 부속서 표지는 채택 문법과 **합집합**으로 쓴다.
    app = [m.start() for m in _APPENDIX.finditer(text)]
    if not name and len(app) < _MIN_APPENDIX:
        return [(None, text)]

    starts = [m.start() for m in pat.finditer(text)] if name else []
    starts = sorted(set(starts) | set(app))
    if not starts:
        return [(None, text)]

    out = []

    head = text[:starts[0]].strip()
    if head:
        out.append((None, head))

    bounds = starts + [len(text)]
    for i in range(len(bounds) - 1):
        seg = text[bounds[i]:bounds[i + 1]]
        if not seg.strip():
            continue
        head, _, rest = seg.partition("\n")
        out.append(_label(head, rest))
    return out


#------------------------------------------------------------------
# 제목 줄을 (이름표, 본문)으로 가르기
#=> 번호절 문서에서는 **제목 줄이 곧 내용**인 경우가 많다.
#
#     14.2 가족이 유해를 운구할 경우 가족 1인에 대하여 왕복여비로 …
#
#   이것을 통째로 이름표에 넣으면 접두가 길어져 본문 예산을 잡아먹고,
#   문장이 이름표와 본문으로 갈라져 읽기도 나빠진다. 그렇다고 잘라 버리면
#   **내용이 사라진다.**
#   → 긴 줄은 번호만 이름표로 쓰고 **줄 전체를 본문에 남긴다.**
#
# -in: head = 절 첫 줄
# -in: rest = 나머지
#
# -out: (이름표 또는 None, 본문)
#------------------------------------------------------------------
def _label(head, rest):
    flat = " ".join(head.split())
    if not flat:
        return None, rest

    if len(flat) <= _TITLE_MAX:
        # 마크다운 '#' 는 이름표에서 떼어 낸다.
        return flat.lstrip("#").strip() or None, rest

    m = _NUMBERING.match(flat)
    return (m.group(1).strip() if m else None), head + "\n" + rest


_TITLE_MAX = 40            # 이보다 길면 제목이 아니라 문장으로 본다
_NUMBERING = re.compile(r"^(제\s*\d+\s*조|#{1,6}|[\dA-Z]+(?:\.\d+)*\.?)")


#------------------------------------------------------------------
# 표 머리글 찾기 (M3 — 실패 분석에서 가장 큰 항목)
#=> 표 행만 담긴 청크는 머리글이 없으면 해석이 불가능하다.
#
#     | 내역 | 휴가(일) | 금액(원) |     ← 이 줄이 다른 청크에 있으면
#     | 본인 결혼 | 5 | 500,000 |        5가 일수인지 금액인지 알 수 없다
#
#   실측에서 출장비품 45% · 계약문서 47% · 점검확인서 50% 로, 표·양식
#   문서가 생성 실패의 최대 집단이었다(REPORT §20.6).
#
# -in: lines = 절 본문을 줄 단위로 나눈 목록
#
# -out: {줄 번호: 그 줄이 속한 표의 머리글 줄} — 표가 없으면 {}
#------------------------------------------------------------------
def table_headers(lines):
    out, header, run = {}, None, False
    for i, ln in enumerate(lines):
        if _TABLE_LINE.match(ln):
            if not run:
                run = True
                # 표가 다시 시작될 때, 그 줄이 **머리글처럼 생겼을 때만**
                # 새 머리글로 삼는다. 값이 든 줄을 머리글로 착각하면
                # ("| 본인 사망 | - |") 뒤따르는 행이 엉뚱한 이름표를 단다.
                # 그런 경우엔 직전 머리글을 계속 쓴다 — 표가 중간에
                # 소제목으로 끊긴 것뿐이기 때문이다.
                if _looks_like_header(ln):
                    header = ln.strip()
                    continue
            if header:
                out[i] = header
        else:
            run = False
    return out


#------------------------------------------------------------------
# 머리글처럼 생겼는가
#=> 머리글 칸은 이름표라 숫자만으로 이루어지지 않는다. 금액·일수가 든 줄은
#   값 행이다.
#
# -in: line = 표 한 줄
#
# -out: bool
#------------------------------------------------------------------
def _looks_like_header(line):
    cells = [c.strip() for c in line.strip().strip("|").split("|")]
    cells = [c for c in cells if c]
    if len(cells) < 2:
        return False
    numeric = sum(1 for c in cells if re.fullmatch(r"[-\d,.\s]+", c))
    return numeric == 0


#------------------------------------------------------------------
# 청크 앞에 붙일 출처 경로
#=> "이 조각이 어느 문서의 어느 대목인가"를 한 줄로 알려 준다.
#   약 10~15토큰을 쓰지만 세 가지를 동시에 얻는다.
#     BM25  — 제목 단어가 색인에 들어가 짧은 질의가 걸린다
#     dense — 임베딩에 문맥이 실린다
#     생성  — 모델이 "지금 보는 것이 제5조(지급 금액)"임을 안다
#
# -in: title   = 문서 제목(보통 파일명)
# -in: section = 절 제목(없으면 None)
#
# -out: 접두 문자열(붙일 것이 없으면 "")
#------------------------------------------------------------------
def make_prefix(title, section):
    parts = [p for p in (title, section) if p]
    if not parts:
        return ""
    return "[" + " > ".join(parts) + "]\n"
