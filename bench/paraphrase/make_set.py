#------------------------------------------------------------------
# 세트 만들기
#=> 골든셋 문항은 질문만 바꾸고 나머지(정답·근거·쪽)를 그대로 옮긴다. 새 문항은 취업규칙(p27) 9쪽 근거로 만든다.
#
# -in: 없음
#
# -out: 없음 (dataset/paraphrase_pdf30.jsonl)
# -out: error = 골든셋 id 가 없으면 KeyError
#------------------------------------------------------------------
def main():
    golden = {json.loads(l)["id"]: json.loads(l) for l in io.open(GOLDEN, encoding="utf-8") if l.strip()}
    p27_files = [f for g in golden.values() if "p27" in g["doc_ids"] for f in g["source_files"]][:1]
    p01_files = [f for g in golden.values() if "p01" in g["doc_ids"] for f in g["source_files"]][:1]
    rows = []
    for gid, q, swaps in PARA:
        g = golden[gid]
        rows.append({"id": "pp" + gid[1:], "origin_id": gid, "user_input": q, "original_input": g["user_input"],
                     "swaps": swaps, "reference": g["reference"], "reference_contexts": g["reference_contexts"],
                     "reference_pages": g["reference_pages"], "doc_ids": g["doc_ids"],
                     "source_files": g["source_files"], "question_type": g["question_type"]})
    for nid, q, ref, ctx, swaps in NEW:
        # 비교용 '문서 용어로 물은 질문' — 일상어를 모두 문서 용어로 되돌린다
        orig = q
        for colloquial, term in swaps:
            orig = orig.replace(colloquial, term)
        rows.append({"id": "pp" + nid, "origin_id": None, "user_input": q,
                     "original_input": orig, "swaps": swaps, "reference": ref,
                     "reference_contexts": ctx,
                     "reference_pages": [{"doc_id": "p27", "page": 9}] + ([{"doc_id": "p01", "page": 1}] if len(ctx) > 1 else []),
                     "doc_ids": ["p27"] + (["p01"] if len(ctx) > 1 else []),
                     "source_files": p27_files + (p01_files if len(ctx) > 1 else []), "question_type": "single_hop"})
    with io.open(OUT, "w", encoding="utf-8") as f:
        for r in rows:
            f.write(json.dumps(r, ensure_ascii=False) + "\n")
    print("저장", OUT, len(rows), "문항")


if __name__ == "__main__":
    main()
